import { randomUUID } from "node:crypto";

export const REASON_CODES = [
  "BODY_TOO_LARGE", "UNSUPPORTED_MEDIA_TYPE", "ORIGIN_NOT_ALLOWED", "HOST_NOT_ALLOWED", "INVALID_REQUEST",
  "RATE_LIMITED", "CAPACITY_EXCEEDED", "AGENT_RUN_REJECTED", "AGENT_RUN_COMPLETED", "AGENT_RUN_STOPPED",
] as const;
export type ReasonCode = typeof REASON_CODES[number];

export type SecurityEvent = {
  event: "http.request.rejected" | "agent.run.rejected" | "agent.run.finished";
  timestamp: string;
  correlationId: string;
  reasonCode: ReasonCode;
  outcome: "allowed" | "denied" | "stopped";
  status?: number;
  stopReason?: string;
  steps?: number;
  providerAttempts?: number;
  executedToolCalls?: number;
};
export type SecurityLog = (event: Omit<SecurityEvent, "timestamp">) => void;

/**
 * Operational security log. Events are built from a closed set of fields and codes. User input,
 * tool names, prompts, provider output, tokens and stack traces are never copied into an event.
 * The correlation id is generated by the application and grants no access.
 */
export function createSecurityLog(write: (line: string) => void = (line) => console.warn(line), now: () => Date = () => new Date()): SecurityLog {
  return (event) => {
    const safe: SecurityEvent = {
      event: event.event,
      timestamp: now().toISOString(),
      correlationId: event.correlationId,
      reasonCode: event.reasonCode,
      outcome: event.outcome === "allowed" || event.outcome === "stopped" ? event.outcome : "denied",
      ...(event.status !== undefined ? { status: event.status } : {}),
      ...(event.stopReason !== undefined ? { stopReason: event.stopReason } : {}),
      ...(event.steps !== undefined ? { steps: event.steps } : {}),
      ...(event.providerAttempts !== undefined ? { providerAttempts: event.providerAttempts } : {}),
      ...(event.executedToolCalls !== undefined ? { executedToolCalls: event.executedToolCalls } : {}),
    };
    try { write(JSON.stringify(safe)); } catch { /* logging must never change the outcome */ }
  };
}

export const newCorrelationId = (): string => `w08-${randomUUID().slice(0, 8)}`;
